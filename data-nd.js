/* ---------------- 工具 ---------------- */
function ndShuffle(arr, seed) {
  const a = arr.slice();
  let s = (seed * 9301 + 49297) % 233280;
  const rnd = () => { s = (s * 9301 + 49297) % 233280; return s / 233280; };
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function ndTier(v) {
  if (v < 35) return 'lo';
  if (v < 65) return 'mid';
  if (v < 80) return 'hi';
  return 'top';
}

/* 由各维读数判定类型（供 app.js 与校验脚本共用） */
function ndPickType(dims) {
  const v = k => {
    const d = dims.find(x => x.k === k);
    return d ? d.val : 0;
  };
  const hiN = dims.filter(d => d.val >= 70).length;
  if (hiN >= 4) return 'wildcard';
  if (v('sen') >= 68 && v('soc') >= 62) return 'antenna';
  const top = dims.slice().sort((a, b) => b.val - a.val)[0];
  if (top.val >= 65) return ND_DIM_TYPE[top.k];
  return 'balanced';
}
